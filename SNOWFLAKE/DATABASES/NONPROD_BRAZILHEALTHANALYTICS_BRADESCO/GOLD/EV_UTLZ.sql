		, A.CODIGO_CONTRATO as CD_APLC
		, A.CODIGO_LOCAL_EMPRESA_OPERADORA as CD_EMPR_GRPO
		, A.DESCRICAO_GENERO AS FL_SEXO
		, A.IDADE_BENEFICIARIO as NR_IDDE
		, A.FAIXA_ETARIA AS NM_FAIX_ETRA
		,CASE
			WHEN DESCRICAO_ELEGIBILIDADE = 'TITULAR' THEN 'T'
			WHEN DESCRICAO_ELEGIBILIDADE = 'DEPENDENTE' THEN 'D'
			WHEN DESCRICAO_ELEGIBILIDADE IS NOT NULL THEN 'D'
		END 
		AS NM_CATG_USRO   
		,A.OBSERVACAO as PLANO_AON_2 
		, 0 as ARH_COD -- somente para a empresa FEMSA KOF
	FROM GOLD.TESTE_SINISTRO_UNIFICADO  A 
