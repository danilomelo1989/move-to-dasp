		, A.COD_TUSS   AS CD_TUSS
		, A.COD_CBHPM  AS CD_CBHPM
		, A.PROC_PRINC   AS PROC_PRINC
		, A.CATEGORIA  AS CATEGORIA
		, A.TIPO_INTERNACAO  AS TIPO_INTERNACAO
		, A.REGIME_DIARIA   AS REGIME_DIARIA
		, A.TIPO_ENTRADA_INTERNACAO AS TIPO_ENTRADA
		, A.CRONICO AS CRONICOS
		, A.GRUPO  AS GRUPO
		/* CAMPOS COMENTADOS PARA PERMITIR QUE O BUG DE CATEGORIA SEJA RESOLVIDO NA TABELA DE CLASSIFICACAO */
		/* 
		, IFNULL(A.DS_SRVC_ABREVIADA , PROCEDIMENTOS_RANK.DS_SRVC_ABREVIADA)  AS DS_SRVC2
		, IFNULL(A.COD_TUSS , PROCEDIMENTOS_RANK.COD_TUSS)  AS CD_TUSS
		, IFNULL(A.COD_CBHPM , PROCEDIMENTOS_RANK.COD_CBHPM)  AS CD_CBHPM
		, IFNULL(A.PROC_PRINC , PROCEDIMENTOS_RANK.PROC_PRINC)  AS PROC_PRINC
		, IFNULL(A.CATEGORIA , PROCEDIMENTOS_RANK.CATEGORIA)  AS CATEGORIA
		, IFNULL(A.TIPO_INTERNACAO , PROCEDIMENTOS_RANK.TIPO_INTERNACAO)  AS TIPO_INTERNACAO
		, IFNULL(A.REGIME_DIARIA , PROCEDIMENTOS_RANK.REGIME_DIARIA)  AS REGIME_DIARIA
		, TIPO_ENTRADA_INTERNACAO AS TIPO_ENTRADA
		, IFNULL(A.CRONICO , PROCEDIMENTOS_RANK.CRONICO)  AS CRONICOS
		, IFNULL(A.GRUPO , PROCEDIMENTOS_RANK.GRUPO)  AS GRUPO
		*/
