		,FN_CREATE_COD_USRO(NOME_BENEFICIARIO , DATA_NASCIMENTO , 1 )  as CD_USRO1
		,FN_CREATE_COD_USRO(NOME_BENEFICIARIO , DATA_NASCIMENTO , 2 )   AS CD_USRO2 
		,A.CODIGO_OPERADORA as CD_OPRD
		,A.CODIGO_EMPRESA
		,A.DATA_REFERENCIA as DT_REFR
		,A.CODIGO_CNPJ_PRESTADOR as COD_PRESTADOR
		,A.NOME_PRESTADOR as NM_LCAL_UTLZ
		,A.NOME_EVENTO as NM_EVNT
		, DESCRICAO_ESPECIALIDADE AS NM_ESPC
		,A.CODIGO_PROCEDIMENTO AS CD_SRVC
