		-- , VALOR_RECIBO AS VL_RCBO -- confirmar nome original
		, A.VALOR_COPARTICIPACAO  AS VL_CO_PART
		, A.QUANTIDADE_PROCEDIMENTO AS QT_SRVC
		, '00' AS CD_DIVISAO -- SOMENTE PARA JBS E FEMSA
		, A.CHAVE_TERAPIA_COMPLEXA_AON AS ID_TER_COMPL_AON 
		, A.CHAVE_PRONTO_SOCORRO_AON AS ID_PS_AON
